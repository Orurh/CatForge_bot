var boldComedyScenes = []banterScene{
	{"пошлая двусмысленность", "Первый хвастается, что может всю ночь без остановки: звучит как интимный подвиг. Второй уточняет, что речь про храп, и весь двор это подтвердит. Пошлый заход и облом в конце, без описаний секса; сформулируй по-своему."},
	{"нежность по-дворовому", "Первый просит хотя бы немного романтики или прелюдии перед очередным наездом. Второй добавляет нелепую церемонность перед грубым посылом. Например, обходительность оказывается только подготовкой к ругани; саму шутку придумай, не повторяй пример про шёпот."},
}

func idleBanterScene(slot int64, bold bool) (string, string) {
	count := len(idleComedyScenes)
	if bold {
		count += len(boldComedyScenes)
	}
	// Shift the rotation each day so overnight quiet hours do not hide the same scenes forever.
	index := int((slot + slot/12) % int64(count))
	if index < 0 {
		index += count
	}
	var scene banterScene
	if index < len(idleComedyScenes) {
		scene = idleComedyScenes[index]
	} else {
		scene = boldComedyScenes[index-len(idleComedyScenes)]
	}
	setup := scene.setup
	if bold {
		setup += " Тон bold: прямой грубый наезд и ответный удар с запиканным матом. Бери из замысла повод, а собственную острую концовку придумай без утешительного примирения и книжных метафор."
	}
	return scene.topic, setup
}
